/** YouTube captions. See docs/sources/youtube_captions.md. */
import { FlashData } from '@flashdata-dev/sdk';
import { command, integerOption, isMain, reportUsage, run, saveJSON } from './_support.mjs';

export async function main(argv = process.argv.slice(2)) {
  const args = command(
    'YouTube captions',
    argv,
    {
      language: { type: 'string', default: 'en' },
      auto: { type: 'boolean', default: false },
      segments: { type: 'string', default: '3' },
    },
    '[video_id]',
  );
  if (!args) return;
  const { values, positionals } = args;
  const client = new FlashData({ apiKey: process.env.FLASHDATA_API_KEY });
  const response = await client.youtube.captions({
    video_id: positionals[0] ?? 'dQw4w9WgXcQ',
    language: values.language,
    auto: values.auto,
  });
  for (const track of response.results) {
    console.log(track.languageCode, '| automatic:', track.isAutoGenerated);
    for (const segment of (track.segments ?? []).slice(
      0,
      integerOption(values.segments, '--segments'),
    ))
      console.log(segment.start, segment.end, segment.text);
  }
  reportUsage(response);
  await saveJSON(response, values.output);
}

if (isMain(import.meta.url)) await run(main);
